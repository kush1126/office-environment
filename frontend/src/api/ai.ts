import api from './client';
import axios from 'axios';
import { useAuthStore } from '@/store/authStore';

export interface ChatMessage {
  id: string;
  company_id: string;
  user_id: string;
  role: 'user' | 'assistant';
  content: string;
  created_at: string;
  model?: string;
}

const getHistoryKey = (companyId?: string) => {
  const cid = companyId || useAuthStore.getState().activeCompanyId || 'default';
  return `office_os_ai_history_${cid}`;
};

export const getChatHistory = async (companyId?: string): Promise<{ messages: ChatMessage[] }> => {
  try {
    const response = await api.get<{ messages: ChatMessage[] }>('/ai/history');
    if (response.data && response.data.messages) {
      return response.data;
    }
    throw new Error('No history returned');
  } catch {
    // Offline local storage fallback
    const key = getHistoryKey(companyId);
    const stored = localStorage.getItem(key);
    const messages: ChatMessage[] = stored ? JSON.parse(stored) : [];
    return { messages };
  }
};

export const sendChatMessage = async (message: string, companyId?: string): Promise<ChatMessage> => {
  const cid = companyId || useAuthStore.getState().activeCompanyId || 'default';
  const user = useAuthStore.getState().user;
  const isRSquare = cid === 'c1111111-1111-1111-1111-111111111111';
  const companyName = isRSquare ? 'RSquare Services' : 'KYP Pharma';
  const companyDomain = isRSquare ? 'Cloud, Software & IT Solutions' : 'Pharmaceutical & Healthcare Supply Chain';

  // 1. Try backend API first
  try {
    const response = await api.post<ChatMessage>('/ai/chat', { message });
    if (response.data && response.data.content) {
      return response.data;
    }
  } catch {
    // Fall back to direct local offline Ollama
  }

  // 2. Direct Local Offline Ollama Interaction
  try {
    // Check available local models
    let selectedModel = 'qwen2.5:7b';
    try {
      const tagsRes = await axios.get('/ollama/api/tags');
      const models = tagsRes.data?.models || [];
      const modelNames = models.map((m: any) => m.name);
      if (modelNames.some((n: string) => n.includes('qwen2.5:7b'))) {
        selectedModel = 'qwen2.5:7b';
      } else if (modelNames.some((n: string) => n.includes('gemma3:4b'))) {
        selectedModel = 'gemma3:4b';
      }
    } catch {
      selectedModel = 'qwen2.5:7b';
    }

    const systemPrompt = `You are the private AI Business Intelligence Assistant for ${companyName} (${companyDomain}).
You are operating in a 100% offline, air-gapped system. No data leaves this device.
You have access to assist the System Administrator (${user?.full_name || 'Admin'}) with:
- Business data calculations, margins, GST analysis, and financial reasoning.
- Product inventory, order tracking, and client inquiries.
- Accurate and structured markdown responses.
Maintain strict confidentiality for ${companyName}. Answer calculations directly and clearly.`;

    const chatResponse = await axios.post('/ollama/api/chat', {
      model: selectedModel,
      messages: [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: message }
      ],
      stream: false
    }, { timeout: 60000 });

    const content = chatResponse.data?.message?.content || 'No response generated by local LLM.';

    const aiMessage: ChatMessage = {
      id: typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : `msg-${Date.now()}`,
      company_id: cid,
      user_id: user?.id || 'admin',
      role: 'assistant',
      content,
      created_at: new Date().toISOString(),
      model: selectedModel
    };

    // Save to isolated local history
    const key = getHistoryKey(companyId);
    const stored = localStorage.getItem(key);
    const history: ChatMessage[] = stored ? JSON.parse(stored) : [];
    
    // Add user message and assistant message
    const userMsg: ChatMessage = {
      id: typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : `user-${Date.now()}`,
      company_id: cid,
      user_id: user?.id || 'admin',
      role: 'user',
      content: message,
      created_at: new Date().toISOString()
    };
    history.push(userMsg);
    history.push(aiMessage);
    localStorage.setItem(key, JSON.stringify(history));

    return aiMessage;
  } catch (err: any) {
    console.error('Local LLM error:', err);
    return {
      id: `err-${Date.now()}`,
      company_id: cid,
      user_id: user?.id || 'admin',
      role: 'assistant',
      content: `⚠️ The local offline AI engine is initializing or loading the model. Please verify Ollama is active. Error: ${err.message || 'Offline call failed'}`,
      created_at: new Date().toISOString(),
      model: 'offline'
    };
  }
};
